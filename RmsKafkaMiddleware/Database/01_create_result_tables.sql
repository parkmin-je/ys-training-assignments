USE YsRmsDB;
GO
SET ANSI_NULLS ON;
SET QUOTED_IDENTIFIER ON;
GO

CREATE TABLE dbo.TB_RMS_RESULT (
  RESULT_ID    BIGINT IDENTITY(1,1) NOT NULL PRIMARY KEY,
  EVENT_TIME   DATETIME2(3) NOT NULL,
  EQUIP_ID     NVARCHAR(50) NOT NULL,
  RECIPE_ID    NVARCHAR(50) NOT NULL,
  CREATED_AT   DATETIME2(3) NOT NULL DEFAULT SYSDATETIME(),
  CONSTRAINT FK_RESULT_EQUIP FOREIGN KEY (EQUIP_ID)
    REFERENCES dbo.TB_EQUIPMENT(EQUIP_ID),
  CONSTRAINT FK_RESULT_RECIPE FOREIGN KEY (RECIPE_ID)
    REFERENCES dbo.TB_RMS_RECIPE(RECIPE_ID)
);

CREATE TABLE dbo.TB_RMS_RESULT_PARAMETER (
  RESULT_ID       BIGINT NOT NULL,
  PARAMETER_ID    NVARCHAR(50) NOT NULL,
  PARAMETER_VALUE NVARCHAR(500) NOT NULL,
  CREATED_AT      DATETIME2(3) NOT NULL DEFAULT SYSDATETIME(),
  CONSTRAINT PK_RESULT_PARAMETER PRIMARY KEY (RESULT_ID, PARAMETER_ID),
  CONSTRAINT FK_RESULT_PARAMETER FOREIGN KEY (RESULT_ID)
    REFERENCES dbo.TB_RMS_RESULT(RESULT_ID) ON DELETE CASCADE
);
GO
